"""Turn the Salesforce "AIM Campus Upcoming" .xls export into a SQL file for the Supabase SQL Editor.

Usage:  python tools/import_sessions.py "AIM_Campus_Upcoming_PP_V1-....xls"
Output: supabase/imports/import_<report date>.sql   (paste into SQL Editor, Run)

Standard library only. The .xls is really an HTML table, so it is parsed as HTML.
"""
import html.parser, json, pathlib, re, sys

LOCATIONS = {"Sydney": "Sydney", "Melbourne": "Melbourne", "Brisbane": "Brisbane",
             "Adelaide": "Adelaide", "Canberra": "Canberra", "Virtual Session": "Live virtual"}
# "<course> [(Virtual)] <XX> <d-m-yyyy> [suffix]"
NAME = re.compile(r"^(?P<course>.*?)\s*(?:\((?i:virtual)\)\s*)?\s(?P<code>[A-Z]{2})\s+(?P<date>\d{1,2}-\d{1,2}-\d{4})(?:\s+\S+)?$")


class Rows(html.parser.HTMLParser):
    def __init__(self):
        super().__init__(); self.rows, self.row, self.cell = [], None, None
    def handle_starttag(self, tag, attrs):
        if tag == "tr": self.row = []
        elif tag == "td" and self.row is not None: self.cell = []
    def handle_endtag(self, tag):
        if tag == "td" and self.cell is not None:
            self.row.append(" ".join("".join(self.cell).split())); self.cell = None
        elif tag == "tr" and self.row is not None:
            self.rows.append(self.row); self.row = None
    def handle_data(self, data):
        if self.cell is not None: self.cell.append(data)


def iso(d):  # 20/10/2026 -> 2026-10-20
    day, month, year = d.split("/")
    return f"{year}-{int(month):02d}-{int(day):02d}"


def main(path):
    p = Rows(); p.feed(pathlib.Path(path).read_text(encoding="utf-8", errors="replace"))
    out, loc, problems, report_date = [], None, [], "unknown"
    for r in p.rows:
        if not r: continue
        if r[0].startswith("Generated By:"):
            m = re.search(r"(\d{1,2})/(\d{1,2})/(\d{4})", r[0])
            if m: report_date = f"{m[3]}-{int(m[2]):02d}-{int(m[1]):02d}"
        if r[0].startswith("Campus Location:"):
            loc = r[0].split(":", 1)[1].strip(); continue
        if r[0] != "Active" or len(r) < 11 or not r[3]: continue
        ref = r[3]
        m = NAME.match(ref)
        if not m or loc not in LOCATIONS:
            problems.append(ref); continue
        out.append({"ref": ref, "course": m["course"].strip(), "location": LOCATIONS[loc],
                    "start_date": iso(r[4]), "end_date": iso(r[5]), "n": int(r[7] or 1),
                    "occupancy": int(r[8] or 0), "capacity": int(r[9] or 0)})
    if problems:
        print(f"Could not read {len(problems)} rows:", *problems[:20], sep="\n  ")
        sys.exit(1)
    if not out:
        print("No session rows found. Is this the 'AIM Campus Upcoming' report?"); sys.exit(1)

    dest = pathlib.Path(__file__).resolve().parent.parent / "supabase" / "imports" / f"import_{report_date}.sql"
    dest.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    dest.write_text(f"-- {len(out)} sessions from {pathlib.Path(path).name}\n"
                    f"select jsonb_pretty(public.apply_session_import($json${body}$json$::jsonb));\n", encoding="utf-8")
    print(f"{len(out)} sessions -> {dest}")


if __name__ == "__main__":
    if len(sys.argv) != 2: sys.exit(__doc__)
    main(sys.argv[1])
