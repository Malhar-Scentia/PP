alter table public.allocations
  add column source text not null default 'admin' check (source in ('admin', 'self'));

-- Every non-cancelled allocation holds one seat, dated or not.
create or replace function public.seats_used(cid uuid)
returns integer language sql stable security definer set search_path = public as $$
  select count(*)::int from allocations where client_id = cid and status <> 'cancelled';
$$;
revoke all on function public.seats_used(uuid) from public;

-- Enforced in a trigger so admin inserts and employee bookings share one rule.
-- The FOR UPDATE on the client row serialises concurrent bookings, so the last seat can't be sold twice.
create or replace function public.allocations_seat_check()
returns trigger language plpgsql security definer set search_path = public as $$
declare v_total int;
begin
  if new.status = 'cancelled' then return new; end if;
  if tg_op = 'UPDATE' and old.status <> 'cancelled' then return new; end if;
  select seats_purchased into v_total from clients where id = new.client_id for update;
  if seats_used(new.client_id) >= v_total then
    raise exception 'no_seats' using errcode = 'P0001',
      detail = format('%s of %s seats used', seats_used(new.client_id), v_total);
  end if;
  return new;
end $$;

create trigger allocations_seat_check
  before insert or update of status on public.allocations
  for each row execute function public.allocations_seat_check();

create or replace function public.seat_summary(p_client uuid)
returns table (purchased int, used int, remaining int)
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_client_admin(p_client) then raise exception 'forbidden' using errcode = '42501'; end if;
  return query
    select c.seats_purchased, seats_used(c.id), greatest(c.seats_purchased - seats_used(c.id), 0)
    from clients c where c.id = p_client;
end $$;
revoke all on function public.seat_summary(uuid) from public;
grant execute on function public.seat_summary(uuid) to authenticated;

-- ─── Employee access ─────────────────────────────────────────────────────────
-- An employee is any signed-in user whose verified email matches a learner row.
-- The admin's People list is therefore the access list.

create or replace function public.jwt_email()
returns citext language sql stable as $$ select nullif(auth.jwt() ->> 'email', '')::citext $$;

create policy "self read" on public.learners
  for select to authenticated using (email = public.jwt_email());

create policy "self read" on public.allocations
  for select to authenticated using (
    exists (select 1 from public.learners l where l.id = learner_id and l.email = public.jwt_email())
  );
