-- ─── Notification outbox ─────────────────────────────────────────────────────
-- One row per employee action. A Database Webhook on INSERT calls the notify-booking
-- edge function. Seat numbers are snapshotted inside the booking transaction.

create table public.booking_events (
  id                   bigint generated by default as identity primary key,
  client_id            uuid not null references public.clients(id) on delete cascade,
  allocation_id        uuid references public.allocations(id) on delete set null,
  learner_id           uuid not null references public.learners(id) on delete cascade,
  kind                 text not null check (kind in ('booked', 'rescheduled', 'cancelled')),
  session_id           bigint references public.sessions(id),
  previous_session_id  bigint references public.sessions(id),
  seats_purchased      int not null,
  seats_used           int not null,
  created_at           timestamptz not null default now(),
  emailed_at           timestamptz
);
create index booking_events_client_idx on public.booking_events (client_id, created_at desc);

alter table public.booking_events enable row level security;
create policy "admin read" on public.booking_events
  for select to authenticated using (public.is_client_admin(client_id));
revoke insert, update, delete on public.booking_events from anon, authenticated;

create or replace function public.log_booking_event(a public.allocations, p_kind text, p_session bigint, p_prev bigint)
returns void language sql security definer set search_path = public as $$
  insert into booking_events (client_id, allocation_id, learner_id, kind, session_id, previous_session_id, seats_purchased, seats_used)
  select a.client_id, a.id, a.learner_id, p_kind, p_session, p_prev, c.seats_purchased, seats_used(c.id)
  from clients c where c.id = a.client_id;
$$;
revoke all on function public.log_booking_event(public.allocations, text, bigint, bigint) from public;

-- ─── Employee RPCs ───────────────────────────────────────────────────────────

-- Book, or move an existing booking/undated allocation for the same course to this session.
create or replace function public.book_session(p_client uuid, p_session bigint)
returns json language plpgsql security definer set search_path = public as $$
declare
  v_learner learners;
  v_sess    sessions;
  v_alloc   allocations;
  v_prev    bigint;
  v_kind    text;
begin
  select * into v_learner from learners where client_id = p_client and email = jwt_email();
  if not found then raise exception 'not_on_list' using errcode = 'P0001'; end if;

  select * into v_sess from sessions where id = p_session;
  if not found or v_sess.start_date < (now() at time zone 'Australia/Sydney')::date then
    raise exception 'session_unavailable' using errcode = 'P0001';
  end if;

  select * into v_alloc from allocations
   where learner_id = v_learner.id and course_id = v_sess.course_id and status <> 'cancelled'
   for update;

  if found then
    if v_alloc.status = 'completed' then raise exception 'already_completed' using errcode = 'P0001'; end if;
    if v_alloc.session_id = p_session then raise exception 'already_booked' using errcode = 'P0001'; end if;
    v_prev := v_alloc.session_id;
    v_kind := case when v_prev is null then 'booked' else 'rescheduled' end;
    update allocations set session_id = p_session, status = 'booked'
     where id = v_alloc.id returning * into v_alloc;
  else
    insert into allocations (client_id, learner_id, course_id, session_id, status, source)
    values (p_client, v_learner.id, v_sess.course_id, p_session, 'booked', 'self')
    returning * into v_alloc;
    v_kind := 'booked';
  end if;

  perform log_booking_event(v_alloc, v_kind, p_session, v_prev);
  return json_build_object('allocation_id', v_alloc.id, 'kind', v_kind);
end $$;

-- Self-booked: cancel and free the seat. Admin-allocated: drop the date, keep the seat.
create or replace function public.cancel_booking(p_allocation uuid)
returns json language plpgsql security definer set search_path = public as $$
declare v_alloc allocations; v_start date; v_prev bigint;
begin
  select a.* into v_alloc from allocations a join learners l on l.id = a.learner_id
   where a.id = p_allocation and l.email = jwt_email() and a.status in ('allocated', 'booked')
   for update of a;
  if not found then raise exception 'not_found' using errcode = 'P0001'; end if;

  select start_date into v_start from sessions where id = v_alloc.session_id;
  if v_start is not null and v_start <= (now() at time zone 'Australia/Sydney')::date then
    raise exception 'too_late' using errcode = 'P0001';
  end if;
  if v_alloc.session_id is null and v_alloc.source = 'admin' then
    raise exception 'nothing_to_cancel' using errcode = 'P0001';
  end if;

  v_prev := v_alloc.session_id;
  if v_alloc.source = 'self' then
    update allocations set status = 'cancelled' where id = v_alloc.id returning * into v_alloc;
  else
    update allocations set session_id = null, status = 'allocated' where id = v_alloc.id returning * into v_alloc;
  end if;

  perform log_booking_event(v_alloc, 'cancelled', null, v_prev);
  return json_build_object('allocation_id', v_alloc.id, 'status', v_alloc.status);
end $$;

revoke all on function public.book_session(uuid, bigint), public.cancel_booking(uuid) from public;
grant execute on function public.book_session(uuid, bigint), public.cancel_booking(uuid) to authenticated;
