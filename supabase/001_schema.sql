-- AIM short course calendar: schema + RLS
-- Run once in the Supabase SQL editor (or `supabase db push`).

create extension if not exists citext;

-- ─── Catalog (AIM-owned, public read) ────────────────────────────────────────

create table public.subjects (
  id    smallint generated by default as identity primary key,
  name  text not null unique
);

create table public.locations (
  id          smallint generated by default as identity primary key,
  name        text not null unique,
  is_virtual  boolean not null default false,
  sort_order  smallint not null default 0
);

create table public.courses (
  id    smallint generated by default as identity primary key,
  name  text not null unique
);

-- subject_id lives on the session: the source data assigns some courses to
-- different subjects depending on the run (e.g. Contract Management).
create table public.sessions (
  id             bigint generated by default as identity primary key,
  course_id      smallint not null references public.courses(id),
  subject_id     smallint not null references public.subjects(id),
  location_id    smallint not null references public.locations(id),
  start_date     date not null,
  end_date       date not null,
  session_count  smallint not null default 1 check (session_count >= 0),
  limited        boolean not null default false,
  updated_at     timestamptz not null default now(),
  check (end_date >= start_date)
);
create index sessions_start_idx  on public.sessions (start_date);
create index sessions_course_idx on public.sessions (course_id, start_date);

-- ─── Tenancy ─────────────────────────────────────────────────────────────────

create table public.clients (
  id             uuid primary key default gen_random_uuid(),
  slug           text not null unique check (slug ~ '^[a-z0-9-]+$'),
  name           text not null,
  logo_url       text,
  contact_name   text,
  contact_email  text,
  contact_phone  text,
  created_at     timestamptz not null default now()
);

create table public.client_admins (
  client_id  uuid not null references public.clients(id) on delete cascade,
  user_id    uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (client_id, user_id)
);

-- People the client admin manages. Not auth users (yet); email links them later.
create table public.learners (
  id          uuid primary key default gen_random_uuid(),
  client_id   uuid not null references public.clients(id) on delete cascade,
  full_name   text not null check (length(trim(full_name)) > 0),
  email       citext not null,
  team        text,
  created_at  timestamptz not null default now(),
  unique (client_id, email),
  unique (id, client_id)           -- target for the composite FK below
);

create type public.allocation_status as enum ('allocated', 'booked', 'completed', 'cancelled');

-- session_id null = allocated to the course, date not chosen yet.
create table public.allocations (
  id          uuid primary key default gen_random_uuid(),
  client_id   uuid not null,
  learner_id  uuid not null,
  course_id   smallint not null references public.courses(id),
  session_id  bigint references public.sessions(id) on delete set null,
  status      public.allocation_status not null default 'allocated',
  notes       text,
  created_by  uuid references auth.users(id) default auth.uid(),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  -- composite FK guarantees the learner belongs to the same client as the row
  foreign key (learner_id, client_id) references public.learners(id, client_id) on delete cascade,
  foreign key (client_id) references public.clients(id) on delete cascade
);
create index allocations_client_idx  on public.allocations (client_id, created_at desc);
create index allocations_learner_idx on public.allocations (learner_id);
create unique index allocations_one_per_course
  on public.allocations (learner_id, course_id)
  where status <> 'cancelled';

-- Keep session/course consistent and stamp updated_at.
create or replace function public.allocations_guard()
returns trigger language plpgsql as $$
begin
  if new.session_id is not null then
    select course_id into new.course_id from public.sessions where id = new.session_id;
  end if;
  new.updated_at := now();
  return new;
end $$;

create trigger allocations_guard
  before insert or update on public.allocations
  for each row execute function public.allocations_guard();

-- ─── RLS ─────────────────────────────────────────────────────────────────────

-- security definer so policies can read client_admins without recursing through its own RLS
create or replace function public.is_client_admin(cid uuid)
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from client_admins where client_id = cid and user_id = auth.uid());
$$;
revoke all on function public.is_client_admin(uuid) from public;
grant execute on function public.is_client_admin(uuid) to authenticated;

alter table public.subjects      enable row level security;
alter table public.locations     enable row level security;
alter table public.courses       enable row level security;
alter table public.sessions      enable row level security;
alter table public.clients       enable row level security;
alter table public.client_admins enable row level security;
alter table public.learners      enable row level security;
alter table public.allocations   enable row level security;

-- Catalog + client branding: readable by anyone with the anon key. Writes via dashboard/service role only.
create policy "catalog read" on public.subjects  for select using (true);
create policy "catalog read" on public.locations for select using (true);
create policy "catalog read" on public.courses   for select using (true);
create policy "catalog read" on public.sessions  for select using (true);
create policy "branding read" on public.clients  for select using (true);

create policy "own memberships" on public.client_admins
  for select to authenticated using (user_id = auth.uid());

create policy "admin rw" on public.learners
  for all to authenticated
  using (public.is_client_admin(client_id))
  with check (public.is_client_admin(client_id));

create policy "admin rw" on public.allocations
  for all to authenticated
  using (public.is_client_admin(client_id))
  with check (public.is_client_admin(client_id));

-- Anon gets no column-level access to private data.
revoke all on public.learners, public.allocations, public.client_admins from anon;
